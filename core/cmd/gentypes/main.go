func structTag(tag *ast.BasicLit) reflect.StructTag {
	if tag == nil {
		return ""
	}
	value, err := strconv.Unquote(tag.Value)
	if err != nil {
		return ""
	}
	return reflect.StructTag(value)
}

func hasOption(options, option string) bool {
	for _, part := range strings.Split(options, ",") {
		if part == option {
			return true
		}
	}
	return false
}

func optionalMark(optional bool) string {
	if optional {
		return "?"
	}
	return ""
}

// tsProperty quotes a JSON name only when it is not a valid TypeScript identifier.
func tsProperty(name string) string {
	if name == "" {
		return `""`
	}
	if !isIdentifierStart(rune(name[0])) {
		return strconv.Quote(name)
	}
	for _, char := range name[1:] {
		if !isIdentifierPart(char) {
			return strconv.Quote(name)
		}
	}
	return name
}

func isIdentifierStart(char rune) bool {
	return char == '_' || char == '$' || (char >= 'a' && char <= 'z') || (char >= 'A' && char <= 'Z')
}

func isIdentifierPart(char rune) bool {
	return isIdentifierStart(char) || (char >= '0' && char <= '9')
}

func exprString(expr ast.Expr) string {
	var buf bytes.Buffer
	if err := printer.Fprint(&buf, token.NewFileSet(), expr); err != nil {
		return fmt.Sprintf("%T", expr)
	}
	return buf.String()
}
