// aliasTypes are named scalar types with string constants. The generator emits
// their literals as a union, so the renderer keeps the exact value set.
var aliasTypes = []typeRef{
	{modulePath + "/core/internal/contract", "Platform", "WirePlatform"},
	{modulePath + "/core/internal/downloads", "State", "WireDownloadState"},
	{modulePath + "/core/internal/types", "LauncherKind", "WireLauncherKind"},
}

type typeRef struct {
	pkgPath string
	name    string
	tsName  string
}

func (ref typeRef) key() string { return ref.pkgPath + "." + ref.name }

// pkgInfo is one parsed Go package. Import aliases are per file, so files keep
// their own alias map.
type pkgInfo struct {
	path   string
	name   string
	dir    string
	types  map[string]*typeInfo
	consts map[string][]string
}

type fileInfo struct {
	imports map[string]string
}

type typeInfo struct {
	spec *ast.TypeSpec
	file *fileInfo
	pkg  *pkgInfo
}

type generator struct {
	root     string
	packages map[string]*pkgInfo
	structs  map[string]typeRef
	aliases  map[string]typeRef
	fset     *token.FileSet
}

type tsField struct {
	jsonName string
	tsType   string
	optional bool
}

func main() {
	root := flag.String("root", ".", "repository root")
	out := flag.String("out", defaultOut, "output file, relative to root")
	check := flag.Bool("check", false, "exit non-zero when the output file is stale")
	flag.Parse()

	data, err := generate(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gentypes:", err)
		os.Exit(1)
	}
	path := filepath.Join(*root, *out)
	if *check {
		current, err := os.ReadFile(path)
		if err != nil {
			fmt.Fprintln(os.Stderr, "gentypes:", err)
			os.Exit(1)
		}
		if !bytes.Equal(current, data) {
			fmt.Fprintf(os.Stderr, "gentypes: %s is stale; run go run ./core/cmd/gentypes\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "gentypes:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gentypes:", err)
		os.Exit(1)
	}
}

// generate parses the Go packages and returns the complete TypeScript file.
func generate(root string) ([]byte, error) {
	g := &generator{
		root:     root,
		packages: map[string]*pkgInfo{},
		structs:  map[string]typeRef{},
		aliases:  map[string]typeRef{},
		fset:     token.NewFileSet(),
	}
	for _, ref := range structTypes {
		if _, exists := g.structs[ref.key()]; exists {
			return nil, fmt.Errorf("duplicate struct %s", ref.key())
		}
		g.structs[ref.key()] = ref
	}
	for _, ref := range aliasTypes {
		if _, exists := g.aliases[ref.key()]; exists {
			return nil, fmt.Errorf("duplicate alias %s", ref.key())
		}
		g.aliases[ref.key()] = ref
	}
	for importPath := range packageDirs {
		if err := g.loadPackage(importPath); err != nil {
			return nil, err
		}
	}

	var buf bytes.Buffer
	fmt.Fprintln(&buf, generatedTag)
	fmt.Fprintln(&buf, "// Regenerate with: go run ./core/cmd/gentypes")
	fmt.Fprintln(&buf, "//")
	fmt.Fprintln(&buf, "// Field names, optionality and nullability follow the json tags in the Go source.")
	fmt.Fprintln(&buf)

	lastPkg := ""
	for _, ref := range structTypes {
		pkg := g.packages[ref.pkgPath]
		decl := pkg.types[ref.name]
		if decl == nil {
			return nil, fmt.Errorf("struct %s.%s not found", pkg.name, ref.name)
		}
		if lastPkg != pkg.path {
			fmt.Fprintf(&buf, "// %s\n\n", pkg.dir)
			lastPkg = pkg.path
		}
		fields, err := g.structFields(decl, map[string]bool{})
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&buf, "/** %s.%s, from %s. */\n", pkg.name, ref.name, g.typeFile(decl))
		fmt.Fprintf(&buf, "export interface %s {\n", ref.tsName)
		for _, field := range fields {
			fmt.Fprintf(&buf, "\t%s%s: %s;\n", tsProperty(field.jsonName), optionalMark(field.optional), field.tsType)
		}
		fmt.Fprintln(&buf, "}")
		fmt.Fprintln(&buf)
	}

	for _, ref := range aliasTypes {
		pkg := g.packages[ref.pkgPath]
		decl := pkg.types[ref.name]
		if decl == nil {
			return nil, fmt.Errorf("type %s.%s not found", pkg.name, ref.name)
		}
		values := pkg.consts[ref.name]
		fmt.Fprintf(&buf, "/** %s.%s, from %s. */\n", pkg.name, ref.name, g.typeFile(decl))
		if len(values) > 0 {
			quoted := make([]string, len(values))
			for i, value := range values {
				quoted[i] = strconv.Quote(value)
			}
			fmt.Fprintf(&buf, "export type %s = %s;\n\n", ref.tsName, strings.Join(quoted, " | "))
			continue
		}
		underlying, _, err := g.typeExpression(decl.spec.Type, decl.file, decl.pkg)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&buf, "export type %s = %s;\n\n", ref.tsName, underlying)
	}

	out := bytes.TrimRight(buf.Bytes(), "\n")
	return append(out, '\n'), nil
}

// loadPackage parses the non-test Go files of one package.
func (g *generator) loadPackage(importPath string) error {
	dir, ok := packageDirs[importPath]
	if !ok {
		return fmt.Errorf("package %s has no folder", importPath)
	}
	entries, err := os.ReadDir(filepath.Join(g.root, dir))
	if err != nil {
		return err
	}
	pkg := &pkgInfo{
		path:   importPath,
		dir:    dir,
		types:  map[string]*typeInfo{},
		consts: map[string][]string{},
	}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(g.fset, filepath.Join(g.root, dir, name), nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if pkg.name == "" {
			pkg.name = file.Name.Name
		}
		info := &fileInfo{imports: importAliases(file)}
		for _, node := range file.Decls {
			switch decl := node.(type) {
			case *ast.GenDecl:
				switch decl.Tok {
				case token.TYPE:
					for _, spec := range decl.Specs {
						typeSpec, ok := spec.(*ast.TypeSpec)
						if !ok {
							continue
						}
						pkg.types[typeSpec.Name.Name] = &typeInfo{spec: typeSpec, file: info, pkg: pkg}
					}
				case token.CONST:
					collectStringConstants(pkg, decl)
				}
			}
		}
	}
	if pkg.name == "" {
		return fmt.Errorf("package %s has no Go files", dir)
	}
	g.packages[importPath] = pkg
	return nil
}

func importAliases(file *ast.File) map[string]string {
	aliases := map[string]string{}
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			continue
		}
		name := ""
		if spec.Name != nil {
			name = spec.Name.Name
		}
		if name == "" {
			name = path[strings.LastIndex(path, "/")+1:]
		}
		aliases[name] = path
	}
	return aliases
}

// collectStringConstants records the literals of typed string constants, which
// become the union members of an alias type.
func collectStringConstants(pkg *pkgInfo, decl *ast.GenDecl) {
	for _, spec := range decl.Specs {
		valueSpec, ok := spec.(*ast.ValueSpec)
		if !ok || valueSpec.Type == nil {
			continue
		}
		typeName, ok := valueSpec.Type.(*ast.Ident)
		if !ok {
			continue
		}
		for _, value := range valueSpec.Values {
			lit, ok := value.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				continue
			}
			text, err := strconv.Unquote(lit.Value)
			if err != nil {
				continue
			}
			pkg.consts[typeName.Name] = append(pkg.consts[typeName.Name], text)
		}
	}
}

func (g *generator) typeFile(decl *typeInfo) string {
	position := g.fset.Position(decl.spec.Pos())
	rel, err := filepath.Rel(g.root, position.Filename)
	if err != nil {
		return position.Filename
	}
	return filepath.ToSlash(rel)
}

// structFields flattens embedded structs, as encoding/json does, and converts
// each json tag to one TypeScript property.
func (g *generator) structFields(decl *typeInfo, seen map[string]bool) ([]tsField, error) {
	key := decl.pkg.path + "." + decl.spec.Name.Name
	if seen[key] {
		return nil, fmt.Errorf("embedded struct cycle at %s", key)
	}
	seen[key] = true
	defer delete(seen, key)

	structType, ok := decl.spec.Type.(*ast.StructType)
	if !ok {
		return nil, fmt.Errorf("%s.%s is not a struct", decl.pkg.name, decl.spec.Name.Name)
	}
	var fields []tsField
	for _, field := range structType.Fields.List {
		if len(field.Names) == 0 {
			embedded, err := g.embeddedDecl(field.Type, decl.file, decl.pkg)
			if err != nil {
				return nil, err
			}
			nested, err := g.structFields(embedded, seen)
			if err != nil {
				return nil, err
			}
			fields = append(fields, nested...)
			continue
		}
		tag := structTag(field.Tag)
		jsonTag := tag.Get("json")
		if jsonTag == "-" {
			continue
		}
		name, options, _ := strings.Cut(jsonTag, ",")
		optional := hasOption(options, "omitempty")
		for _, fieldName := range field.Names {
			jsonName := name
			if jsonName == "" {
				jsonName = fieldName.Name
			}
			tsType, err := g.fieldType(field.Type, decl.file, decl.pkg, optional)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", decl.spec.Name.Name, fieldName.Name, err)
			}
			fields = append(fields, tsField{jsonName: jsonName, tsType: tsType, optional: optional})
		}
	}
	return fields, nil
}

func (g *generator) embeddedDecl(expr ast.Expr, file *fileInfo, pkg *pkgInfo) (*typeInfo, error) {
	name, target, err := g.resolveNamed(expr, file, pkg)
	if err != nil {
		return nil, err
	}
	if target == nil {
		return nil, fmt.Errorf("embedded type %s is not a named struct", name)
	}
	return target, nil
}

// fieldType renders one property type. omitempty pointers and collections are
// optional rather than nullable because JSON leaves them out entirely.
func (g *generator) fieldType(expr ast.Expr, file *fileInfo, pkg *pkgInfo, optional bool) (string, error) {
	base, nullable, err := g.typeExpression(expr, file, pkg)
	if err != nil {
		return "", err
	}
	if nullable && !optional && base != "unknown" {
		return base + " | null", nil
	}
	return base, nil
}

// typeExpression renders a Go type as TypeScript. nullable reports a pointer,
// slice or map, which encoding/json sends as null when it is nil.
func (g *generator) typeExpression(expr ast.Expr, file *fileInfo, pkg *pkgInfo) (string, bool, error) {
	switch value := expr.(type) {
	case *ast.StarExpr:
		base, _, err := g.typeExpression(value.X, file, pkg)
		return base, true, err
	case *ast.ArrayType:
		if value.Len != nil {
			return "", false, fmt.Errorf("fixed-size arrays are not supported")
		}
		base, nullable, err := g.typeExpression(value.Elt, file, pkg)
		if err != nil {
			return "", false, err
		}
		if nullable {
			base = "(" + base + " | null)"
		}
		return base + "[]", true, nil
	case *ast.MapType:
		key, _, err := g.typeExpression(value.Key, file, pkg)
		if err != nil {
			return "", false, err
		}
		if key != "string" {
			return "", false, fmt.Errorf("map key %s is not a string", key)
		}
		valueType, _, err := g.typeExpression(value.Value, file, pkg)
		if err != nil {
			return "", false, err
		}
		return "Record<string, " + valueType + ">", true, nil
	case *ast.InterfaceType:
		if len(value.Methods.List) != 0 {
			return "", false, fmt.Errorf("non-empty interfaces are not supported")
		}
		return "unknown", false, nil
	case *ast.Ident:
		if primitive, ok := primitiveTypes[value.Name]; ok {
			return primitive, false, nil
		}
		return g.namedType(value.Name, file, pkg)
	case *ast.SelectorExpr:
		alias, ok := value.X.(*ast.Ident)
		if !ok {
			return "", false, fmt.Errorf("unsupported selector %s", exprString(value))
		}
		importPath, ok := file.imports[alias.Name]
		if !ok {
			return "", false, fmt.Errorf("unknown import alias %s", alias.Name)
		}
		switch {
		case importPath == "time" && value.Sel.Name == "Time":
			return "string", false, nil
		case importPath == "encoding/json" && value.Sel.Name == "RawMessage":
			return "unknown", false, nil
		}
		targetPkg := g.packages[importPath]
		if targetPkg == nil {
			return "", false, fmt.Errorf("package %s is not loaded", importPath)
		}
		decl := targetPkg.types[value.Sel.Name]
		if decl == nil {
			return "", false, fmt.Errorf("type %s.%s not found", targetPkg.name, value.Sel.Name)
		}
		return g.namedDecl(decl)
	default:
		return "", false, fmt.Errorf("unsupported Go type %T", expr)
	}
}

func (g *generator) namedType(name string, file *fileInfo, pkg *pkgInfo) (string, bool, error) {
	decl := pkg.types[name]
	if decl == nil {
		return "", false, fmt.Errorf("type %s.%s not found", pkg.name, name)
	}
	return g.namedDecl(decl)
}

func (g *generator) namedDecl(decl *typeInfo) (string, bool, error) {
	key := decl.pkg.path + "." + decl.spec.Name.Name
	if _, isStruct := decl.spec.Type.(*ast.StructType); isStruct {
		ref, ok := g.structs[key]
		if !ok {
			return "", false, fmt.Errorf("struct %s.%s is not in structTypes; add it to the generator", decl.pkg.name, decl.spec.Name.Name)
		}
		return ref.tsName, false, nil
	}
	if ref, ok := g.aliases[key]; ok {
		return ref.tsName, false, nil
	}
	return g.typeExpression(decl.spec.Type, decl.file, decl.pkg)
}

func (g *generator) resolveNamed(expr ast.Expr, file *fileInfo, pkg *pkgInfo) (string, *typeInfo, error) {
	switch value := expr.(type) {
	case *ast.Ident:
		return value.Name, pkg.types[value.Name], nil
	case *ast.SelectorExpr:
		alias, ok := value.X.(*ast.Ident)
		if !ok {
			return "", nil, fmt.Errorf("unsupported selector")
		}
		importPath, ok := file.imports[alias.Name]
		if !ok {
			return "", nil, fmt.Errorf("unknown import alias %s", alias.Name)
		}
		targetPkg := g.packages[importPath]
		if targetPkg == nil {
			return "", nil, fmt.Errorf("package %s is not loaded", importPath)
		}
		return value.Sel.Name, targetPkg.types[value.Sel.Name], nil
	default:
		return "", nil, fmt.Errorf("embedded field is not a named type")
	}
}

